def _state_vals(store, e1, r):
    """bits/w (1-bit mask), PPL, KL, flips (%) of a state, or -- each."""
    if r is None:
        return ["--"] * 4
    sto, wt = r.get("storage") or {}, r.get("wikitext2") or {}
    f9 = (e1["by_sid"].get(r["state_id"], {}).get("flips", {}).get("pooled9") or {}).get("flips")
    return [num(sto.get("bitmap"), 2), num(wt.get("ppl"), 2), num(wt.get("kl"), 3), num(100 * f9 if finite(f9) else None, 1)]


def table_main_rows(store, e1, fr, missing):
    lines = [GEN, "% Model & Configuration & bits/w (1-bit mask) & PPL & KL & Flips (%) \\\\  (booktabs body rows)\n",
             "% PPL: WikiText-2; KL: mean token KL(dense || model) on WikiText-2, nats; flips: share of items whose\n",
             "% correctness differs from the dense model, pooled over the 9 zero-shot tasks (v2 metric); seed 0;\n",
             "% best order per cell = lowest WikiText-2 perplexity among joint, P->Q, Q->P (all three required).\n"]
    body = []
    for model in store.models():
        rows = [("dense", store.dense(model), "dense state")]
        for b in store.quant_bits(model):
            rows.append((f"{b}-bit", store.quant_only(model, b), f"{b}-bit quant-only state"))
        for s, b in store.cells(model, 0, PAPER_ORDERS):
            best = fr["best"].get((model, s, b))
            if best:
                rows.append((f"{cell_tex(s, b)}, {ORDER_TEX[best['order']]}", store.states[best["state_id"]], ""))
            else:
                rows.append((cell_tex(s, b), None, f"{cell_label(s, b)}: not all three orders available"))
        if body:
            body.append("\\midrule\n")
        for i, (label, r, why) in enumerate(rows):
            vals = _state_vals(store, e1, r)
            if r is None:
                missing.add("paper/generated/table_main_rows.tex", f"{model} {label}", why + " (printed as --)")
            body.append(" & ".join([model if i == 0 else "", label] + vals) + " \\\\\n")
    return "".join(lines + body)


def table_kl_flips(store, e1, missing):
    lines = [GEN, "\\begin{tabular}{llcccccc}\n", "\\toprule\n",
             " & & \\multicolumn{3}{c}{KL to dense (nats/token)} & \\multicolumn{3}{c}{Flips vs dense (\\%)} \\\\\n",
             "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\n",
             "Model & $s$ + $b$ & " + " & ".join(ORDER_TEX[o] for o in PAPER_ORDERS) + " & "
             + " & ".join(ORDER_TEX[o] for o in PAPER_ORDERS) + " \\\\\n", "\\midrule\n"]
    first = True
    for model in store.models():
        cells = store.cells(model, 0, PAPER_ORDERS)
        if not first:
            lines.append("\\midrule\n")
        first = False
        for i, (s, b) in enumerate(cells):
            kl, fl = {}, {}
            for o in PAPER_ORDERS:
                r = store.get(model, o, s, b, 0)
                kl[o] = (r.get("wikitext2") or {}).get("kl") if r else None
                f = (e1["by_sid"].get(r["state_id"], {}).get("flips", {}).get("pooled9") or {}).get("flips") if r else None
                fl[o] = 100 * f if finite(f) else None
                if r is None:
                    missing.add("paper/generated/table_kl_flips.tex", f"{model} {cell_label(s, b)} {ORDER_TXT[o]}",
                                "state not available yet (printed as --)")

            def cells_fmt(d, nd):
                ok = all(finite(v) for v in d.values())
                best = min(d.values()) if ok else None
                return [("\\textbf{" + num(d[o], nd) + "}") if ok and d[o] == best else num(d[o], nd) for o in PAPER_ORDERS]
            lines.append(" & ".join([model if i == 0 else "", cell_tex(s, b)] + cells_fmt(kl, 3) + cells_fmt(fl, 1)) + " \\\\\n")
    lines += ["\\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


def table_mechanism_rows(store, e2res, e3rows, missing):
    lines = [GEN, "% Model & Cell & grid re-fitted & pruning-only mask & both \\\\  (booktabs body rows)\n",
             "% Share of the Q->P penalty over P->Q removed by each ablation arm. First value: E2, sum of layer errors\n",
             "% on one shared Hessian per layer (ablation_same_hessian.summarize). In parentheses, when the cell is in\n",
             "% E3: WikiText-2 perplexity of full sequential runs, (ppl_QP - ppl_arm) / (ppl_QP - ppl_PQ).\n",
             "% n/a: no penalty in that cell (Q->P not worse than P->Q); --: not available yet.\n",
             f"% $^\\dagger$: penalty under {SMALL_PENALTY_PCT:g}% of the P->Q error (E2: summed layer error; E3: perplexity), so the\n",
             "% shares divide by a small number and are ill-conditioned.\n",
             "% $^\\ddagger$ after the model name: E2 lines for that model are still incomplete (see the coverage lines below).\n"]
    e2c = {(c["model"], c["cell"]): c for c in e2res["cells"]}
    e3c = {(r["model"], r["cell"]): r for r in e3rows}
    cells = e2res.get("cell_list") or sorted({(c["sparsity"], c["bits"]) for c in e2res["cells"]}, key=lambda c: (-c[1], c[0]))
    body = []
    models = [c["model"] for c in e2res["coverage"]] or store.models()
    cov = {c["model"]: c for c in e2res["coverage"]}
    for m in models:
        c = cov.get(m, {})
        lines.append(f"% E2 coverage {m}: {c.get('n_lines', 0)} of {c.get('n_expected', '?')} planned layer lines\n")
    for model in models:
        c = cov.get(model, {})
        partial = bool(c.get("n_lines")) and bool(c.get("n_missing"))
        e3cells = {(r["sparsity"], r["bits"]) for r in e3rows if r["model"] == model}
        allcells = sorted(set((round(s, 4), b) for s, b in cells) | e3cells, key=lambda c: (-c[1], c[0]))
        if body:
            body.append("\\midrule\n")
        for i, (s, b) in enumerate(allcells):
            k = (model, cell_label(s, b))
            c2, c3 = e2c.get(k), e3c.get(k)
            vals = []
            small2 = c2 is not None and finite(c2.get("qp_penalty_pct_of_pq")) and 0 < c2["qp_penalty_pct_of_pq"] < SMALL_PENALTY_PCT
            pq3 = c3.get("wt_ppl_p_then_q") if c3 else None
            small3 = bool(c3) and finite(c3.get("wt_ppl_penalty")) and finite(pq3) and \
                0 < 100 * c3["wt_ppl_penalty"] / pq3 < SMALL_PENALTY_PCT
            for arm in MECH_ARMS:
                if c2 is None or not c2.get("n_layers"):
                    v = "--"
                    missing.add("paper/generated/table_mechanism_rows.tex", f"{model} {cell_label(s, b)} E2", "no E2 lines yet")
                elif c2.get("qp_penalty_sum") is not None and c2["qp_penalty_sum"] <= 0:
                    v = "n/a"
                else:
                    v = pct_tex(c2.get(f"penalty_removed_{arm}_pct")) + ("$^\\dagger$" if small2 else "")
                if (s, b) in e3cells:
                    pen = c3.get("wt_ppl_penalty") if c3 else None
                    w = c3.get(f"wt_ppl_removed_{arm}_pct") if c3 else None
                    if finite(pen) and pen <= 0:
                        v3 = "n/a"
                    else:
                        v3 = pct_tex(w) + ("$^\\dagger$" if small3 and finite(w) else "")
                        if v3 == "--":
                            missing.add("paper/generated/table_mechanism_rows.tex", f"{model} {cell_label(s, b)} E3 {ORDER_TXT[arm]}",
                                        "full runs not available yet (printed as --)")
                    v = f"{v} ({v3})"
                vals.append(v)
            name = (model + ("$^\\ddagger$" if partial else "")) if i == 0 else ""
            body.append(" & ".join([name, cell_tex(s, b)] + vals) + " \\\\\n")
    return "".join(lines + body)


def frontier_dat(store, fr, paths, missing):
    out = {}
    for model in store.models():
        pts = [p for p in fr["points"] if p["model"] == model]
        for kind, sel, fname in (("quant", [p for p in pts if p["kind"] == "quant"], f"fig_frontier_quant_{model}.dat"),
                                 ("sparse", [p for p in pts if p.get("best_in_cell")], f"fig_frontier_sparse_{model}.dat")):
            sel = sorted([p for p in sel if finite(p["wt_ppl"])], key=lambda p: (-(p["bits_bitmap"] or 0), -(p["bits"] or 0)))
            head = ["# generated by scripts/make_tables.py from results/v2 -- do not edit by hand",
                    f"# {model}, seed 0, " + ("quantization only" if kind == "quant" else "pruning + quantization, best order per cell (lowest WikiText-2 ppl)"),
                    "# bits = nominal bit-width b; bits_tcr = b(1-s) (TCr accounting); bits_mask = bits_tcr + 1-bit mask when s > 0;",
                    "# ppl = WikiText-2 perplexity; kl = KL(dense || model) per token on WikiText-2 (nats); scale/zero overhead excluded",
                    "# rows: " + ("; ".join(f"{p['state_id']}" for p in sel) if sel else "none yet")]
            rows = ["bits bits_tcr bits_mask ppl kl"]
            for p in sel:
                rows.append(" ".join(f"{v:.6g}" if finite(v) else "nan" for v in
                                     (p["bits"], p["bits_tcr"], p["bits_bitmap"], p["wt_ppl"], p["wt_kl"])))
            if not sel:
                missing.add("paper/generated/" + fname, model, "no point yet (header only)")
            path = os.path.join(paths.generated, fname)
            write_text(path, "\n".join(head + rows) + "\n")
            out[fname] = len(sel)
    return out


# ----------------------------------------------------------------------------- macros
class Macros:
    """Macro registry. A macro is either listed on its own row of MACROS.md (name, value, meaning, source) or,
    for per-state quantities, placed in a matrix (grid=...): row = state (with its file and state_id),
    column = quantity (with its field or derivation), name = \\res + column + model tag + row tag."""

    def __init__(self):
        self.rows, self.names = [], set()

    def add(self, section, name, value, meaning, source, grid=None):
        name = "res" + name
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name not letters-only: {name}")
        if name in self.names:
            raise ValueError(f"duplicate macro {name}")
        self.names.add(name)
        self.rows.append({"section": section, "name": name, "value": value, "meaning": meaning, "source": source,
                          "grid": grid})

    def tex(self):
        out = [GEN, "% One \\newcommand per number the text may quote. -- = not available yet. Documented in MACROS.md.\n",
               "% \\resInputRows{generated/table_main_rows.tex}: reads a body-rows file with the TeX primitive (expandable),\n",
               "% so \\bottomrule may follow it directly inside a tabular (LaTeX's \\input is not expandable there).\n",
               "\\providecommand{\\resInputRows}[1]{\\csname @@input\\endcsname #1 }\n"]
        sec = None
        for r in self.rows:
            if r["section"] != sec:
                sec = r["section"]
                out.append(f"\n% ---- {sec}\n")
            out.append(f"\\newcommand{{\\{r['name']}}}{{{r['value']}}}\n")
        return "".join(out)

    def md(self, header):
        out, order, by = [header], [], {}
        for r in self.rows:
            if r["section"] not in by:
                order.append(r["section"])
            by.setdefault(r["section"], []).append(r)
        for sec in order:
            R = by[sec]
            out.append(f"\n## {sec}\n")
            if all(r["grid"] for r in R):
                g0 = R[0]["grid"]
                cols, rows, val = [], [], {}
                for r in sorted(R, key=lambda x: x["grid"].get("col_index", 0)):
                    g = r["grid"]
                    if g["col"] not in cols:
                        cols.append(g["col"])
                    if g["row"] not in [x["row"] for x in rows]:
                        rows.append(g)
                    val[(g["row"], g["col"])] = r["value"]
                out.append(f"Macro = `\\res` + column + `{g0['model_tag']}` + row tag (e.g. "
                           f"`\\res{cols[0]}{g0['model_tag']}{rows[0]['row']}`). Row source: the state's result line;"
                           " column source: below the table.\n")
                out.append("| Row tag | State | Source | " + " | ".join(cols) + " |")
                out.append("|---|---|---|" + "---|" * len(cols))
                for g in rows:
                    cells = [val.get((g["row"], c), "") for c in cols]
                    out.append(f"| `{g['row']}` | {g['row_label']} | {g['row_source']} | "
                               + " | ".join(f"`{v}`" if v else "" for v in cells) + " |")
                out.append("\nColumns:\n")
                seen = set()
                for r in R:
                    c = r["grid"]["col"]
                    if c not in seen:
                        seen.add(c)
                        out.append(f"- `{c}`: {r['grid']['col_meaning']}")
            else:
                out += ["| Macro | Value | Meaning | Source |", "|---|---|---|---|"]
                for r in R:
                    v = r["value"].replace("|", "\\|")
                    out.append(f"| `\\{r['name']}` | `{v}` | {r['meaning']} | {r['source']} |")
        return "\n".join(out) + "\n"


def _src(store, sid, field):
    if sid and sid in store.states:
        return f"{store.source[sid]}, state `{sid}`, field `{field}`"
    return f"state `{sid}` (planned, not available yet)"


def _configs(store, model, seed=0):
    """(order, s, b) of every seed-0 state of a model that is planned or present, in table order."""
    seen = set()
    for sid, r in list(store.states.items()) + list(store.plan.items()):
        mm = r.get("short") or r["model"].split("/")[-1]
        if mm == model and int(r.get("seed", 0)) == seed:
            seen.add((r["order"], round(float(r["sparsity"]), 4), int(r["bits"])))
    rank = {"dense": 0, "quant": 1, "prune": 2}
    return sorted(seen, key=lambda x: (rank.get(x[0], 3), -x[2], x[1], COMBINED.index(x[0]) if x[0] in COMBINED else 99))


