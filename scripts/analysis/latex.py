def words(n):
    n = int(n)
    if n < 20:
        return ONES[n]
    if n < 100:
        return TENS[n // 10] + (ONES[n % 10] if n % 10 else "")
    if n < 1000:
        return ONES[n // 100] + "Hundred" + (words(n % 100) if n % 100 else "")
    return "".join(ONES[int(d)] for d in str(n))


def model_tag(m):
    if m in MODEL_TAG:
        return MODEL_TAG[m]
    return "".join(words(c) if c.isdigit() else (c if c.isalpha() else "") for c in m)


def config_tag(order, s, b, seed=0):
    if order == "dense":
        t = "Dense"
    elif order == "quant":
        t = "QuantB" + words(b)
    elif order == "prune":
        t = "PruneS" + words(pct(s))
    else:
        t = "S" + words(pct(s)) + "B" + words(b) + ORDER_TAG.get(order, re.sub("[^A-Za-z]", "", order.title()))
    return t + ("Seed" + words(seed) if seed else "")


def cell_tag(s, b):
    return "S" + words(pct(s)) + "B" + words(b)


def num(v, nd):
    return f"{v:.{nd}f}" if finite(v) else "--"


def signed(v, nd):
    return "\\ensuremath{" + f"{v:+.{nd}f}" + "}" if finite(v) else "--"


def sci(v):
    if not finite(v):
        return "--"
    if v == 0:
        return "0"
    m, e = f"{v:.2e}".split("e")
    return "\\ensuremath{" + f"{m}\\times 10^{{{int(e)}}}" + "}"


def pval(v):
    if not finite(v):
        return "--"
    return f"{v:.3f}" if v >= 0.001 else sci(v)


def yesno(v):
    return "--" if v is None else ("yes" if v else "no")


def pct_tex(v, nd=0):
    if not finite(v):
        return "--"
    return ("$-$" if v < 0 else "") + f"{abs(v):.{nd}f}\\%"


def tex_escape(s):
    return str(s).replace("\\", "/").replace("%", "\\%").replace("_", "\\_").replace("&", "\\&").replace("#", "\\#")


