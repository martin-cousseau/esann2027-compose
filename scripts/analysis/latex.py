def _g(r, block, key):
    return ((r or {}).get(block) or {}).get(key)


def _pc(v):
    return 100 * v if finite(v) else None


def _f(b, key):
    f9 = (b.get("flips", {}) or {}).get("pooled9") or {}
    v = f9.get(key)
    if key != "flips":
        v = v / f9["n"] if finite(v) and f9.get("n") else None
    return v


def _sr(b, kind, key, i=0):
    v = b.get(kind, {}).get(key)
    return v[i] if v else None


def macros_states(M, store, e1):
    for model in store.models():
        mt = model_tag(model)
        sec, sec_isr = f"States of {model} (seed 0)", f"I_Sr of the combined states of {model} (seed 0)"
        isr_rows = []
        for order, s, b in _configs(store, model):
            sid = store.sid(model, order, s, b, 0) or store.planned_sid(model, order, s, b, 0)
            r, bs = store.states.get(sid), e1["by_sid"].get(sid, {})
            row = {"model_tag": mt, "row": config_tag(order, s, b), "row_label": store.label(sid),
                   "row_source": (f"`{store.source[sid]}` `{sid}`" if r else f"`{sid}` (planned, not available yet)")}
            for ci, (col, meaning, get) in enumerate(STATE_COLS):
                if col == "FreeZerosPct" and order == "dense":
                    continue
                M.add(sec, col + mt + row["row"], get(r, bs), f"{model} {row['row_label']}: {meaning}",
                      row["row_source"], grid=dict(row, col=col, col_meaning=meaning, col_index=ci))
            if order in COMBINED:
                isr_rows.append((row, bs))
        for row, bs in isr_rows:
            for col, key in ISR_SETS:
                meaning = (f"I_Sr = Sr_PQ - Sr_P Sr_Q ({S.SR_SETS[key]['label']}), P and Q the prune-only and quant-only states"
                           f" at the same s and b; paired bootstrap ({e1['boot']['B']} resamples) gives Lo/Hi; " + ITEMS)
                for suffix, i, what in (("", 0, ""), ("Lo", 1, " 95% interval, lower end"), ("Hi", 2, " 95% interval, upper end")):
                    M.add(sec_isr, col + suffix + mt + row["row"], signed(_sr(bs, "isr", key, i), 3),
                          f"{model} {row['row_label']}: {col}{what}", row["row_source"],
                          grid=dict(row, col=col + suffix, col_meaning=meaning + what, col_index=3 * ISR_SETS.index((col, key)) + i))


def macros_seeds(M, store, e1):
    rows = {(r["model"], r["order"], r["sparsity"], r["bits"]): r for r in e1["seeds"]}
    for v in store.plan.values():  # every configuration planned with more than one seed, present or not
        k = (v["short"], v["order"], round(v["sparsity"], 4), v["bits"])
        if v["seed"] > 0 and k not in rows:
            rows[k] = {"model": k[0], "order": k[1], "sparsity": k[2], "bits": k[3], "seeds": "pending", "n": 0,
                       "wt_ppl_mean": None, "wt_ppl_sd": None}
    for row in sorted(rows.values(), key=lambda r: (r["model"], r["bits"], r["sparsity"], r["order"])):
        mt = model_tag(row["model"])
        ct = mt + config_tag(row["order"], row["sparsity"], row["bits"])
        lab = f"{row['model']} {cell_label(row['sparsity'], row['bits']) if row['order'] in COMBINED else row['order']} {ORDER_TXT.get(row['order'], row['order'])}"
        src = f"reports/analysis/e1_seeds.csv (seeds {row['seeds']})"
        M.add("Calibration seeds", "PplMean" + ct, num(row["wt_ppl_mean"], 2), f"{lab}: mean WikiText-2 ppl over {row['n']} seeds", src)
        M.add("Calibration seeds", "PplSd" + ct, num(row["wt_ppl_sd"], 2), f"{lab}: sample sd of WikiText-2 ppl over {row['n']} seeds", src)


def macros_questions(M, store, q):
    s1, src1 = q["q1_summary"], "reports/analysis/q1_layer_interaction.csv (scripts/analysis/questions.py, from the diags of each line)"
    sec = "Q1: layer-level interaction (seed 0; counts over the E1 grid: core models x E1 cells)"
    M.add(sec, "QOneMaskFirstSub", str(s1["mask_first_subadditive"]), "joint and P->Q combinations sub-additive (ratio of mean errors < 0)", src1)
    M.add(sec, "QOneMaskFirstTotal", str(s1["mask_first_total"]), "joint and P->Q combinations with all three states available", src1)
    for o, ot in (("joint", "Joint"), ("p_then_q", "PQ"), ("q_then_p", "QP")):
        for b, bt in ((4, "BFour"), (3, "BThree"), (None, "")):
            tag = f"{o}_{b}bit" if b else o
            what = f"{ORDER_TXT[o]}{f', {b}-bit cells' if b else ''}"
            M.add(sec, f"QOneRatioMin{ot}{bt}Pct", signed(s1[f"{tag}_min_pct"], 1), f"{what}: smallest I_E/(E_P+E_Q) (%)", src1)
            M.add(sec, f"QOneRatioMax{ot}{bt}Pct", signed(s1[f"{tag}_max_pct"], 1), f"{what}: largest I_E/(E_P+E_Q) (%)", src1)
            M.add(sec, f"QOneSub{ot}{bt}", str(s1[f"{tag}_n_subadditive"]), f"{what}: cells sub-additive", src1)
            M.add(sec, f"QOneSuper{ot}{bt}", str(s1[f"{tag}_n_superadditive"]), f"{what}: cells super-additive", src1)
            M.add(sec, f"QOneCells{ot}{bt}", str(s1[f"{tag}_n"]), f"{what}: cells available", src1)
            v = s1[f"{tag}_layer_share_subadditive"]
            M.add(sec, f"QOneLayerShare{ot}{bt}Pct", num(100 * v if finite(v) else None, 0),
                  f"{what}: sub-additive layer records, matched layer by layer (%)", src1)
            if b:
                for t in LAYER_TYPES:
                    v = s1[f"{tag}_layer_share_{t}"]
                    M.add(sec, f"QOneLayerShare{ot}{bt}{TYPE_TAG[t]}Pct", num(100 * v if finite(v) else None, 0),
                          f"{what}: sub-additive {t} records (%)", src1)
                M.add(sec, f"QOneBlockZeroSuper{ot}{bt}", str(s1[f"{tag}_cells_block0_superadditive"]),
                      f"{what}: cells where block 0 alone is super-additive", src1)
    s2, src2 = q["q2_summary"], "reports/analysis/q2_order_ranking.csv (scripts/analysis/questions.py)"
    sec = "Q2: order ranking (seed 0; counts over the E1 grid: core models x E1 cells)"
    for key, tag in (("wt_ppl", "Ppl"), ("c4_ppl", "PplCFour"), ("wt_kl", "Kl"), ("c4_kl", "KlCFour"), ("flips9", "Flips"),
                     ("sr3_v2", "SrThree"), ("sr9_v2", "SrExt"), ("sr3_paper", "SrPaper")):
        M.add(sec, f"QTwoCells{tag}", str(s2[f"{key}_cells"]), f"cells with all three orders ranked by {key}", src2)
        M.add(sec, f"QTwoQPWorst{tag}", str(s2[f"{key}_qp_worst"]), f"cells where Q->P is strictly worst by {key}", src2)
        for o, ot in (("joint", "Joint"), ("p_then_q", "PQ"), ("q_then_p", "QP")):
            M.add(sec, f"QTwoBest{ot}{tag}", str(s2[f"{key}_best_{o}"]), f"cells where {ORDER_TXT[o]} is best by {key}", src2)
            if key == "wt_ppl":
                for m in [x for x in store.models() if any(g[0] == x for g in PAPER_GRID)]:
                    v = s2.get(f"{key}_best_{o}_{m}")
                    M.add(sec, f"QTwoBest{ot}{tag}{model_tag(m)}", str(v) if v is not None else "--",
                          f"{m}: cells where {ORDER_TXT[o]} has the lowest WikiText-2 ppl", src2)
    M.add(sec, "QTwoMaxRatio", num(s2.get("wt_ppl_max_worst_best_ratio"), 2), "largest worst/best WikiText-2 ppl ratio over cells", src2)
    M.add(sec, "QTwoMaxRatioWhere", tex_escape(s2.get("wt_ppl_max_worst_best_where") or "--"), "where that ratio occurs", src2)
    M.add(sec, "QTwoMaxRatioCFour", num(s2.get("c4_ppl_max_worst_best_ratio"), 2), "largest worst/best C4 ppl ratio over cells", src2)
    M.add(sec, "QTwoAgreeCells", str(s2["agreement_cells"]), "cells ranked by all five metrics (WT2 ppl, C4 ppl, KL, flips, Sr)", src2)
    M.add(sec, "QTwoAgreeAll", str(s2["agreement_identical"]), "cells where the five metrics give the identical ranking", src2)
    for key, tag in (("c4_ppl", "PplCFour"), ("wt_kl", "Kl"), ("flips9", "Flips"), ("sr3_v2", "SrThree")):
        M.add(sec, f"QTwoAgree{tag}", str(s2[f"agree_with_wt_ppl_{key}"]), f"cells where {key} ranks the orders as WikiText-2 ppl does", src2)
        M.add(sec, f"QTwoSameBest{tag}", str(s2[f"same_best_as_wt_ppl_{key}"]), f"cells where {key} picks the same best order", src2)
    for r in q["q2"]:
        ct = model_tag(r["model"]) + cell_tag(r["sparsity"], r["bits"])
        M.add(sec, "QTwoRatio" + ct, num(r.get("wt_ppl_worst_best_ratio"), 2), f"{r['model']} {r['cell']}: worst/best WikiText-2 ppl ratio", src2)
    sec, src3 = "Q3: 4-bit order spread", "reports/analysis/q3_order_spread.csv"
    for r in q["q3"]:
        if r["bits"] != 4 or r["metric"] != "wt_ppl":
            continue
        mt = model_tag(r["model"])
        M.add(sec, f"QThreeSpreadMin{mt}Pct", num(r["spread_min_pct"], 1), f"{r['model']}: smallest (max-min)/min of WikiText-2 ppl over the orders, 4-bit cells (%)", src3)
        M.add(sec, f"QThreeSpreadMax{mt}Pct", num(r["spread_max_pct"], 1), f"{r['model']}: largest 4-bit order spread (%)", src3)
    sf, srcf = q["fp_summary"], "reports/analysis/fp16_vs_fp32.csv (v2 fp32 vs results/merged published values)"
    sec = "fp16 vs fp32 (published v1 vs v2)"
    M.add(sec, "FpCompared", str(sf["n_compared"]), "published configurations (seed 0) with a v2 fp32 counterpart", srcf)
    v = sf.get("max_abs_rel_delta")
    M.add(sec, "FpMaxAbsDeltaPct", num(100 * v if finite(v) else None, 2), "largest |v2 ppl / published ppl - 1| (%)", srcf)
    M.add(sec, "FpMaxAbsDeltaWhere", tex_escape(sf.get("max_where") or "--"), "where it occurs", srcf)
    for m in store.models():
        v = sf.get(f"max_abs_rel_delta_{m}")
        M.add(sec, f"FpMaxAbsDelta{model_tag(m)}Pct", num(100 * v if finite(v) else None, 2), f"{m}: largest |relative ppl difference| (%)", srcf)
    sec = "E3: Q->P penalty removed in full runs (WikiText-2 ppl)"
    for r in q["e3"]:
        ct = model_tag(r["model"]) + cell_tag(r["sparsity"], r["bits"])
        for arm in MECH_ARMS:
            M.add(sec, f"EThreeRemoved{MECH_TAG[arm]}{ct}Pct", signed(r.get(f"wt_ppl_removed_{arm}_pct"), 0),
                  f"{r['model']} {r['cell']}: share of the Q->P ppl penalty removed by {ORDER_TXT[arm]} (%)", "reports/analysis/e3_mechanism.csv")
        M.add(sec, f"EThreeStale{ct}Pct", signed(r.get("wt_ppl_stale_on_pq_pct"), 1),
              f"{r['model']} {r['cell']}: P->Q ppl change with the stale grid (%)", "reports/analysis/e3_mechanism.csv")


def macros_misc(M, store, e1, det, fr, e2res, boolq):
    sec = "Determinism (DET vs the same state in E1)"
    srcd = "reports/analysis/det_determinism.json (results/v2/DET vs the E1 line with the same state_id)"
    d = det[0] if det else {}
    M.add(sec, "DetNllAbsDiff", sci(d.get("nll_sum_abs_diff")), "|wikitext2.nll_sum difference|", srcd)
    M.add(sec, "DetRelErrMaxAbsDiff", sci(d.get("rel_err_max_abs_diff")), "largest |rel_err difference| over layers", srcd)
    M.add(sec, "DetLayers", str(d.get("n_layers_compared")) if d.get("n_layers_compared") is not None else "--", "layers compared", srcd)
    M.add(sec, "DetIdentical", yesno({"identical": True, "differs": False}.get(d.get("status"))), "bit-identical (nll_sum and every rel_err)", srcd)
    sec = "Storage: Q->P 25%+3 vs 3-bit alone, scale overhead"
    for r in fr["identity"]:
        mt = model_tag(r["model"])
        src = "reports/analysis/identity_qp25_3bit.json"
        M.add(sec, f"IdentityQPThree{mt}", yesno(r.get("identical")), f"{r['model']}: Q->P 25%+3 identical to 3-bit (ppl and every rel_err)", src)
        M.add(sec, f"IdentityRelErrMaxDiff{mt}", sci(r.get("rel_err_max_abs_diff")), f"{r['model']}: largest |rel_err difference|", src)
    for b in (4, 3, 2, 8):
        go = [((s.get("storage") or {}).get("group_overhead"), sid) for sid, s in store.states.items()
              if s["order"] == "quant" and int(s["bits"]) == b]
        go = [x for x in go if finite(x[0])]
        M.add(sec, f"GroupOverheadB{words(b)}", num(go[0][0], 3) if go else "--", f"{b}-bit: scale and zero point bits per weight",
              _src(store, go[0][1], "storage.group_overhead") if go else "no state yet")
    sec = "E2: same-Hessian layer ablation"
    srce = "reports/analysis/e2_cells.csv (scripts/analysis/e2.py, formulas of ablation_same_hessian.summarize)"
    rho = {(r["model"], r["cell"], r["arm"]): r for r in e2res["spearman"]}
    have = {(c["model"], c["cell"]): c for c in e2res["cells"] if c.get("n_layers")}
    planned = [(cv["model"], s_, b_) for cv in e2res["coverage"] for s_, b_ in (e2res.get("cell_list") or [])]
    for m, s_, b_ in planned:
        c = have.get((m, cell_label(s_, b_))) or {"model": m, "cell": cell_label(s_, b_), "sparsity": s_, "bits": b_,
                                                  "n_layers": None}
        ct = model_tag(c["model"]) + cell_tag(c["sparsity"], c["bits"])
        lab = f"{c['model']} {c['cell']}"
        M.add(sec, f"ETwoLayers{ct}", str(c["n_layers"]) if c["n_layers"] else "--", f"{lab}: layers in E2", srce)
        for arm in COMBINED:
            at = ORDER_TAG[arm]
            M.add(sec, f"ETwoRatio{at}{ct}Pct", signed(c.get(f"ratio_{arm}_pct"), 1), f"{lab}: {ORDER_TXT[arm]} I_E/(E_P+E_Q), sums over layers (%)", srce)
            v = c.get(f"share_sub_{arm}")
            M.add(sec, f"ETwoSub{at}{ct}Pct", num(100 * v if finite(v) else None, 0), f"{lab}: {ORDER_TXT[arm]} sub-additive layers (%)", srce)
        for arm in ("joint", "p_then_q", "q_then_p"):
            at = ORDER_TAG[arm]
            M.add(sec, f"ETwoBlockZero{at}{ct}Pct", signed(c.get(f"ratio_block0_{arm}_pct"), 1), f"{lab}: {ORDER_TXT[arm]} ratio, block 0 (%)", srce)
            M.add(sec, f"ETwoDeeper{at}{ct}Pct", signed(c.get(f"ratio_deeper_{arm}_pct"), 1), f"{lab}: {ORDER_TXT[arm]} ratio, blocks > 0 (%)", srce)
        M.add(sec, f"ETwoPenalty{ct}Pct", signed(c.get("qp_penalty_pct_of_pq"), 1), f"{lab}: Q->P penalty, % of P->Q summed error", srce)
        for arm in MECH_ARMS:
            M.add(sec, f"ETwoRemoved{MECH_TAG[arm]}{ct}Pct", signed(c.get(f"penalty_removed_{arm}_pct"), 0),
                  f"{lab}: share of the Q->P penalty removed by {ORDER_TXT[arm]} (%)", srce)
        M.add(sec, f"ETwoStale{ct}Pct", signed(c.get("stale_grid_on_pq_pct"), 1), f"{lab}: stale grid imposed on P->Q (% of its error)", srce)
        M.add(sec, f"ETwoMaskQuality{ct}", num(c.get("mask_quality_median"), 2), f"{lab}: median pruning-only error ratio, Q->P mask / SparseGPT mask", srce)
        M.add(sec, f"ETwoJaccard{ct}", num(c.get("mask_jaccard_median"), 2), f"{lab}: median Jaccard overlap of the masks", srce)
        r = rho.get((c["model"], c["cell"], "p_then_q"), {})
        M.add(sec, f"ETwoRho{ct}", signed(r.get("rho"), 2), f"{lab}: Spearman rho, P->Q layer ratio vs h_corr_index", "reports/analysis/e2_spearman.csv")
        M.add(sec, f"ETwoRhoP{ct}", pval(r.get("p")), f"{lab}: p-value of that rho", "reports/analysis/e2_spearman.csv")
    sec = "Task data"
    rate, rec = boolq
    M.add(sec, "BoolqChance", num(rate, 3), "BoolQ chance level = majority-class rate of the validation labels",
          f"reports/analysis/boolq_chance.json ({rec['dataset']} {rec['config']} {rec['split']}, revision {rec['revision'][:12]})" if rec else "unavailable")
    M.add(sec, "BoolqN", str(rec["n"]) if rec else "--", "BoolQ validation labels counted", "reports/analysis/boolq_chance.json" if rec else "unavailable")
    n_items = {}
    for row in e1["tasks"]:
        n_items.setdefault(row["task"], row["n_items"])
    for t in P.ZERO_SHOT_TASKS:
        M.add(sec, f"NItems{TASK_TAG[t]}", str(n_items[t]) if t in n_items else "--", f"{t}: items evaluated per state", "results/v2/items/*.json.gz")
    M.add(sec, "BootB", str(e1["boot"]["B"]), "bootstrap resamples (items within each task)", "scripts/analysis/stats.py, make_tables.py --boot")
    M.add(sec, "NStates", str(len(store.states)), "usable v2 model states (status ok)", "results/v2/*/*.jsonl")
    M.add(sec, "NStatesPlanned", str(len(store.plan)), "model states in the study plan", "scripts/make_queues.py")


def write_all(store, e1, q, det, fr, e2res, boolq, paths, missing):
    G = paths.generated
    write_text(os.path.join(G, "table_main_rows.tex"), table_main_rows(store, e1, fr, missing))
    write_text(os.path.join(G, "table_kl_flips.tex"), table_kl_flips(store, e1, missing))
    write_text(os.path.join(G, "table_mechanism_rows.tex"), table_mechanism_rows(store, e2res, q["e3"], missing))
    dat = frontier_dat(store, fr, paths, missing)
    M = Macros()
    macros_states(M, store, e1)
    macros_seeds(M, store, e1)
    macros_questions(M, store, q)
    macros_misc(M, store, e1, det, fr, e2res, boolq)
    write_text(os.path.join(G, "macros.tex"), M.tex())
    write_text(os.path.join(G, "MACROS.md"), M.md(MACROS_HEADER))
    n_missing = sum(r["value"] == "--" for r in M.rows)
    return {"macros": len(M.rows), "macros_missing": n_missing, "dat": dat}


